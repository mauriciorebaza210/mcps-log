// The ChatGPT dictionary (email-engine/docs/chatgpt/DICTIONARY.md → Plan changes 2026-11-16).
// ee-sync.mjs turns it into email-engine/src/Dictionary.js, so every engine deploy carries
// the current text; the engine then rewrites the Drive copy when the text changes and emails
// Tony when the version goes up (Docs.js). Pure, so tests can run it.
//
// The file must have:  "Version: N (YYYY-MM-DD)"  near the top, and a "## What changed"
// section with one "### Version N — YYYY-MM-DD" heading per version (newest first), each
// followed by "- " bullets in plain words for Tony.
import crypto from 'node:crypto';

export const DICTIONARY_PATH = 'email-engine/docs/chatgpt/DICTIONARY.md';

export function parseDictionary(md) {
  const errors = [];
  const v = md.match(/^Version:\s*(\d+)\s*\((\d{4}-\d{2}-\d{2})\)\s*$/m);
  if (!v) errors.push('missing "Version: N (YYYY-MM-DD)" line');
  const version = v ? Number(v[1]) : 0, date = v ? v[2] : '';
  const at = md.search(/^## What changed\s*$/m);
  const changes = [];
  if (at === -1) errors.push('missing "## What changed" section');
  else {
    const rest = md.slice(at).split('\n').slice(1);
    let cur = null;
    for (const line of rest) {
      if (/^## /.test(line)) break;
      const h = line.match(/^### Version (\d+) [—-] (\d{4}-\d{2}-\d{2})\s*$/);
      if (h) { cur = { version: Number(h[1]), date: h[2], items: [] }; changes.push(cur); continue; }
      const b = line.match(/^- (.+)$/);
      if (b && cur) cur.items.push(b[1].trim());
    }
  }
  if (v && !changes.some(c => c.version === version)) errors.push('no "### Version ' + version + ' — <date>" entry under What changed');
  changes.forEach(c => { if (!c.items.length) errors.push('Version ' + c.version + ' has no "- " bullets'); });
  for (let i = 1; i < changes.length; i++) if (changes[i].version >= changes[i - 1].version) errors.push('What changed must list versions newest first');
  if (changes.length && changes[0].version !== version) errors.push('the newest What changed entry (' + changes[0].version + ') must match Version: ' + version);
  return { version, date, changes, errors, hash: crypto.createHash('sha256').update(md).digest('hex') };
}

export function dictionaryJs(md) {
  const d = parseDictionary(md);
  if (d.errors.length) throw new Error(DICTIONARY_PATH + ': ' + d.errors.join('; '));
  return '// GENERATED by scripts/ee-sync.mjs from ' + DICTIONARY_PATH + '. Do not edit; edit the source.\n' +
    'var EE_DICTIONARY = ' + JSON.stringify({ version: d.version, date: d.date, hash: d.hash, changes: d.changes.slice(0, 10), text: md }) + ';\n';
}
